export type DataExportCategory =
  | "account_identity"
  | "athlete_profile_athletics"
  | "academic_and_grades"
  | "nutrition_and_fitness"
  | "deals_and_contracts"
  | "team_and_family_sharing"
  | "documents_and_forg3_signing"
  | "sports_travel_and_events"
  | "scouting_and_recruiting"
  | "communications_and_social"
  | "security_mfa_and_passkeys"
  | "organizations_and_audit";

export interface DataExportManifest {
  exportedAt: string;
  userId: string;
  exportFormatVersion: string;
  recordCounts: Record<DataExportCategory, number>;
  containsImmutableSignedAgreements: boolean;
  privacyNotice: string;
  retentionRules: {
    dealAuditRetentionYears: number;
    notificationRetentionDays: number;
    unexecutedDraftPurgeDays: number;
    tombstonePreservationNote: string;
  };
}

export interface SanitizedExportSummary {
  manifest: DataExportManifest;
  redactedThirdPartyPiiCount: number;
  dataPayloadSizeEstimateBytes: number;
}

export function generateExportManifest(
  userId: string,
  counts: Record<DataExportCategory, number>,
  hasSignedAgreements: boolean,
  timestamp: string = new Date().toISOString()
): DataExportManifest {
  return {
    exportedAt: timestamp,
    userId,
    exportFormatVersion: "2.1.0-GDPR-CCPA-COMPLIANT",
    recordCounts: counts,
    containsImmutableSignedAgreements: hasSignedAgreements,
    privacyNotice:
      "This export contains data generated by and attributed to your account. Third-party private data (such as direct messages written by other parties) has been excluded to preserve mutual privacy rights.",
    retentionRules: {
      dealAuditRetentionYears: 7,
      notificationRetentionDays: 90,
      unexecutedDraftPurgeDays: 30,
      tombstonePreservationNote:
        "Executed agreements, cryptographically hashed signing audit certificates, and ledger records remain retained per legal and tax accounting requirements even after profile anonymization.",
    },
  };
}

export function auditDataExportSanity(
  rawExport: Record<string, unknown>
): {
  isValid: boolean;
  leakedSensitiveFields: string[];
  totalRecordsIncluded: number;
} {
  const leakedSensitiveFields: string[] = [];
  const forbiddenKeys = [
    "password_hash",
    "authenticator_secret",
    "recovery_code_hashes",
    "private_key",
    "token_hash",
    "raw_ssn",
    "raw_bank_account",
  ];

  let recordCount = 0;

  function traverse(obj: unknown, path: string) {
    if (!obj || typeof obj !== "object") return;

    if (Array.isArray(obj)) {
      recordCount += obj.length;
      obj.forEach((item, idx) => traverse(item, `${path}[${idx}]`));
      return;
    }

    for (const [key, val] of Object.entries(obj as Record<string, unknown>)) {
      if (forbiddenKeys.includes(key.toLowerCase())) {
        leakedSensitiveFields.push(`${path}.${key}`);
      }
      traverse(val, `${path}.${key}`);
    }
  }

  traverse(rawExport, "root");

  return {
    isValid: leakedSensitiveFields.length === 0,
    leakedSensitiveFields,
    totalRecordsIncluded: recordCount,
  };
}
