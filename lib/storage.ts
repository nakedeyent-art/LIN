import { createHash, createHmac } from "node:crypto";

/**
 * Private object storage for uploaded files (S3-compatible: AWS S3, MinIO, R2, …), signed with SigV4 and reached only from the server.
 * Nothing here is ever exposed as a public URL: downloads always go through the app's authenticated routes, which stream the bytes.
 * When it is not configured, files stay in Postgres (`document_versions.contents`) exactly as before.
 */
export type StorageConfig = { endpoint: string; bucket: string; region: string; accessKey: string; secretKey: string; pathStyle: boolean };
type Env = Record<string, string | undefined>;

export function storageConfig(env: Env = process.env): StorageConfig | null {
  const endpoint = env.OBJECT_STORAGE_ENDPOINT?.trim(), bucket = env.OBJECT_STORAGE_BUCKET?.trim();
  if (!endpoint && !bucket) return null;
  if (!endpoint || !bucket || !env.OBJECT_STORAGE_ACCESS_KEY || !env.OBJECT_STORAGE_SECRET_KEY) throw new Error("OBJECT_STORAGE_ENDPOINT, OBJECT_STORAGE_BUCKET, OBJECT_STORAGE_ACCESS_KEY and OBJECT_STORAGE_SECRET_KEY must all be set, or none of them.");
  let url: URL;
  try { url = new URL(endpoint); } catch { throw new Error("OBJECT_STORAGE_ENDPOINT must be a URL."); }
  if (url.protocol !== "https:" && !/^(localhost|127\.0\.0\.1)$/.test(url.hostname)) throw new Error("OBJECT_STORAGE_ENDPOINT must use https (plain http is allowed only for a local test server).");
  if (!/^[a-z0-9.-]{3,63}$/.test(bucket)) throw new Error("OBJECT_STORAGE_BUCKET is not a valid bucket name.");
  return { endpoint: url.origin, bucket, region: env.OBJECT_STORAGE_REGION?.trim() || "us-east-1", accessKey: env.OBJECT_STORAGE_ACCESS_KEY, secretKey: env.OBJECT_STORAGE_SECRET_KEY, pathStyle: env.OBJECT_STORAGE_PATH_STYLE !== "0" };
}

const sha256 = (b: Uint8Array | string) => createHash("sha256").update(b).digest("hex");
const hmac = (k: Uint8Array | string, d: string) => createHmac("sha256", k).update(d).digest();
const encodeKey = (key: string) => key.split("/").map(encodeURIComponent).join("/");

/** Object keys are generated by us, never from file names: `documents/<document id>/<version>-<sha256>`. */
export const documentObjectKey = (documentId: string, version: number, hash: string) => `documents/${documentId}/${version}-${hash}`;

/** SigV4 request against the bucket. Returns the response; callers decide what status is acceptable. */
export async function s3Request(cfg: StorageConfig, method: "PUT" | "GET" | "DELETE" | "HEAD", key: string, body?: Uint8Array, contentType?: string, fetchImpl: typeof fetch = fetch): Promise<Response> {
  if (!/^[A-Za-z0-9/_.-]{1,512}$/.test(key) || key.includes("..")) throw new Error("Invalid object key");
  const base = new URL(cfg.endpoint);
  const host = cfg.pathStyle ? base.host : `${cfg.bucket}.${base.host}`;
  const path = cfg.pathStyle ? `/${cfg.bucket}/${encodeKey(key)}` : `/${encodeKey(key)}`;
  const now = new Date(), amzDate = now.toISOString().replace(/[-:]|\.\d{3}/g, ""), day = amzDate.slice(0, 8);
  const payloadHash = sha256(body ?? new Uint8Array());
  const headers: Record<string, string> = { host, "x-amz-content-sha256": payloadHash, "x-amz-date": amzDate };
  if (contentType) headers["content-type"] = contentType;
  const signedNames = Object.keys(headers).sort();
  const canonicalHeaders = signedNames.map((h) => `${h}:${headers[h].trim()}\n`).join(""), signedHeaders = signedNames.join(";");
  const canonical = [method, path, "", canonicalHeaders, signedHeaders, payloadHash].join("\n");
  const scope = `${day}/${cfg.region}/s3/aws4_request`;
  const toSign = ["AWS4-HMAC-SHA256", amzDate, scope, sha256(canonical)].join("\n");
  const kDate = hmac(`AWS4${cfg.secretKey}`, day), kRegion = hmac(kDate, cfg.region), kService = hmac(kRegion, "s3"), kSigning = hmac(kService, "aws4_request");
  const signature = createHmac("sha256", kSigning).update(toSign).digest("hex");
  const auth = `AWS4-HMAC-SHA256 Credential=${cfg.accessKey}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`;
  const { host: _h, ...sendHeaders } = headers; void _h;   // fetch sets host (and content-length, which is deliberately not signed) itself
  return fetchImpl(`${base.protocol}//${host}${path}`, { method, headers: { ...sendHeaders, authorization: auth }, body: body ? new Uint8Array(body) : undefined, signal: AbortSignal.timeout(30_000) });
}

export async function putObject(cfg: StorageConfig, key: string, bytes: Uint8Array, contentType: string, fetchImpl?: typeof fetch): Promise<void> {
  const r = await s3Request(cfg, "PUT", key, bytes, contentType, fetchImpl);
  if (!r.ok) throw new Error(`Object storage rejected the upload (${r.status})`);
}
export async function getObject(cfg: StorageConfig, key: string, fetchImpl?: typeof fetch): Promise<Uint8Array | null> {
  const r = await s3Request(cfg, "GET", key, undefined, undefined, fetchImpl);
  if (r.status === 404) return null;
  if (!r.ok) throw new Error(`Object storage read failed (${r.status})`);
  return new Uint8Array(await r.arrayBuffer());
}
export async function deleteObject(cfg: StorageConfig, key: string, fetchImpl?: typeof fetch): Promise<void> {
  const r = await s3Request(cfg, "DELETE", key, undefined, undefined, fetchImpl);
  if (!r.ok && r.status !== 404) throw new Error(`Object storage delete failed (${r.status})`);
}
